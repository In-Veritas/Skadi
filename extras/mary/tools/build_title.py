"""Embed the supplied Skadi ASCII and bundled Adwaita Mono glyphs in GLSL.

Run after editing banner/skadi.txt; requires Pillow only at generation time.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
rows = (root / 'overrides/banner/skadi.txt').read_text().splitlines()
assert len(rows) == 7
width = max(map(len, rows))
# Shape families: rounded, vertical double bowls, stems, and punctuation.
families = ['oO0', '8B', 'dqb', 'PY', '.:', "'`", '"', '()']
chars = ' ' + ''.join(dict.fromkeys(''.join(families)))
assert set(''.join(rows)) <= set(chars)
font = ImageFont.truetype(str(root / 'payload/share/fonts/mary-adwaita-mono/AdwaitaMono-Regular.ttf'), 15)
masks = []
for c in chars:
    image = Image.new('L', (10, 18))
    ImageDraw.Draw(image).text((0, -1), c, font=font, fill=255)
    masks.extend(sum(1 << x for x in range(10) if image.getpixel((x, y)) >= 85) for y in range(18))
alternates = []
for c in chars:
    family = next((f for f in families if c in f), c)
    alternates.append(chars.index(family[(family.index(c) + 1) % len(family)]))
block = '// BEGIN SKADI ASCII (generated by tools/build_title.py)\n'
block += f'const int TITLE_COLUMNS = {width};\n'
block += 'const int TITLE_CELLS[%d] = int[%d](\n' % (width * 7, width * 7)
block += ',\n'.join('    '+','.join(str(chars.index(c)) for c in row.ljust(width)) for row in rows) + ');\n'
block += 'const int TITLE_ALTERNATES[%d] = int[%d](%s);\n' % (len(chars), len(chars), ','.join(map(str, alternates)))
block += 'const uint TITLE_GLYPHS[%d] = uint[%d](\n' % (len(masks), len(masks))
block += ',\n'.join('    '+','.join(str(v)+'u' for v in masks[i:i+18]) for i in range(0, len(masks), 18)) + ');\n'
block += '// END SKADI ASCII'
p = root / 'overrides/shaders/ocean-dots.glsl'
s = p.read_text()
a = s.index('// BEGIN SKADI ASCII'); b = s.index('// END SKADI ASCII', a) + len('// END SKADI ASCII')
p.write_text(s[:a] + block + s[b:])
print(f'Skadi: {width} columns, 7 rows, {len(chars)} glyphs')
